const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const context = vm.createContext({console});
vm.runInContext(fs.readFileSync('src/r1hands/panel/static/landmark-session.js', 'utf8'), context);
const {validate, Recorder, Playback} = context.LandmarkClip;
const profile = {open: [0,0,0,0,0,0], closed: [1,1,1,1,1,1]};
const hands = [{label:'left',score:0.99,points:Array.from({length:21},()=>[0.1,0.2,0.3]),
  image:Array.from({length:21},()=>({x:0.5,y:0.5}))}];
const recorder = new Recorder(profile, false);
recorder.add({timestamp:1000,hands,inference_ms:10});
recorder.add({timestamp:1100,hands:[],inference_ms:10});
recorder.add({timestamp:1200,hands,inference_ms:10});
const clip=validate(recorder.clip);
assert.equal(clip.frames[0].t,0);
assert.equal(clip.frames[1].hands.length,0,'tracking gaps must survive recording');
profile.open[0]=0.5;
assert.equal(clip.profile.open[0],0,'recording freezes its calibration');
const restored=validate(JSON.parse(JSON.stringify(clip)));
const playback=new Playback(restored);
playback.play(500);
assert.equal(playback.tick(500).length,1);
assert.equal(playback.tick(600)[0].frame.hands.length,0);
playback.pause(650);
assert.equal(playback.tick(5000).length,0);
playback.play(1000);
assert.equal(playback.tick(1050)[0].index,2);
assert.equal(playback.playing,false);
playback.rewind();playback.play(2000);
assert.equal(playback.tick(2200).length,3);
assert.throws(()=>validate({...restored,schema:'unknown'}));
assert.throws(()=>validate({...restored,frames:[restored.frames[1],restored.frames[0]]}));
assert.throws(()=>validate({...restored,profile:{open:[0,0,0,0,0,0],closed:[0,0,0,0,0,0]}}));
assert.throws(()=>validate({...restored,frames:[{t:0,hands:[{...hands[0],score:NaN}]}]}));
assert.equal(recorder.add({timestamp:121001,hands,inference_ms:10}),false);
console.log('Landmark recording, validation, dropout preservation and timed replay passed');
